#!/usr/bin/env python3
"""Assemble the Castellan mockup pages from the component fragments.

Markup components live in ui-mockups/components/, CSS in ui-mockups/styles/,
and the JS source fragments in ui-mockups/scripts/. The build concatenates the
scripts into ui-mockups/app.js and the generated pages are
ui-mockups/console-shell.html (browser window + app) and
ui-mockups/app.html (the app UI without browser chrome).

Usage: python3 ui-mockups/build.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
COMPONENTS = ROOT / "components"
SCRIPTS = ROOT / "scripts"
STYLES = ROOT / "styles"
STYLE_FILES = [
    "app-layout.css",
    "left-rail.css",
    "views.css",
    "right-rail.css",
    "dashboard.css",
    "temp.css",
    "composer.css",
    "pickers.css",
    "archive.css",
    "responsive.css",
]
INCLUDE = re.compile(r"<!--\s*include:\s*([^\s>]+)\s*-->")

THEME = """<script>
(function () {
  var d = document.documentElement;
  var embedded = false;
  try { embedded = window.self !== window.top; } catch (e) { embedded = true; }
  d.classList.add(embedded ? "embedded" : "standalone");
  if (!embedded) {
    var saved = null;
    try { saved = localStorage.getItem("castellan.theme"); } catch (e) {}
    if (saved === "dark" || saved === "light") d.dataset.theme = saved;
    else if (window.matchMedia && matchMedia("(prefers-color-scheme: dark)").matches) d.dataset.theme = "dark";
  }
  addEventListener("message", function (e) {
    if (!e.data || e.data.type !== "mock-theme") return;
    d.dataset.theme = e.data.theme === "dark" ? "dark" : "light";
  });
  function askTheme() { try { window.parent.postMessage({ type: "mock-theme-request" }, "*"); } catch (e) {} }
  askTheme();
  addEventListener("load", askTheme);
})();
</script>"""


def resolve(text, depth=0):
    if depth > 8:
        raise RuntimeError("include nesting too deep")

    def replace(match):
        rel = match.group(1)
        path = COMPONENTS / rel
        if not path.is_file():
            raise FileNotFoundError(f"missing component: {rel}")
        return resolve(path.read_text(), depth + 1)

    return INCLUDE.sub(replace, text)


def page(title, content, browser=False, full=False):
    class_attr = ' class="app-full"' if full else ''
    links = '<link rel="stylesheet" href="mockup.css">'
    if browser:
        links += '\n<link rel="stylesheet" href="browser.css">'
    links += ''.join(f'\n<link rel="stylesheet" href="styles/{name}">' for name in STYLE_FILES)
    return f"""<!DOCTYPE html>
<html lang="en" data-theme="light"{class_attr}>
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="color-scheme" content="light dark">
<meta name="theme-color" media="(prefers-color-scheme: light)" content="#FBF5E6">
<meta name="theme-color" media="(prefers-color-scheme: dark)" content="#171717">
<link rel="icon" href="../logo/LogoLight.svg">
<title>{title}</title>
{links}
{THEME}
</head>
<body>
<div class="stage">
{content}
</div>
<script src="files.js"></script>
<script src="models.js"></script>
<script src="app.js"></script>
</body>
</html>
"""


def build_js():
    files = sorted(SCRIPTS.glob("*.js"))
    if not files:
        raise FileNotFoundError("no scripts found in scripts/")
    body = "\n".join(
        f"/* ================= {path.name} ================= */\n" + path.read_text().rstrip() + "\n"
        for path in files
    )
    bundle = '/* generated by build.py — edit scripts/*.js instead */\n(function () {\n  "use strict";\n\n' + body + "\n})();\n"
    (ROOT / "app.js").write_text(bundle)
    print(f"built app.js from {len(files)} sources")


def main():
    build_js()
    app = resolve((COMPONENTS / "app-shell.html").read_text())
    browser = resolve((COMPONENTS / "browser-window.html").read_text())
    (ROOT / "app.html").write_text(page("Castellan — app mockup", app, full=True))
    (ROOT / "console-shell.html").write_text(page("Castellan — browser preview", browser, browser=True))
    print("built app.html and console-shell.html")


if __name__ == "__main__":
    main()
